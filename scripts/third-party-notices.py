#!/usr/bin/env python3
"""Write, or with --check verify, THIRD-PARTY-NOTICES.txt.

It lists the open-source components compiled into Badi's binaries (the
broker and badictl, resolved from Cargo.lock for the shipped target, and
nlohmann-json in the Fcitx addon) and reproduces each licence text their
packages publish, every identical text once. Build-time crates such as
proc macros are not in a binary and are not listed.
"""
import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "THIRD-PARTY-NOTICES.txt"
TARGET = "x86_64-unknown-linux-gnu"
LICENCE_FILES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")
# Texts a component's published package leaves out, taken from its source tag.
EXTRA_TEXTS = {("whatlang", "0.18.0"): ("packaging/licenses/whatlang-0.18.0-LICENSE",)}
# Compiled into the Fcitx addon from the system's header-only package.
NATIVE = (("nlohmann-json", "3.12.0", "MIT", "https://github.com/nlohmann/json",
           ("packaging/licenses/nlohmann-json-3.12.0-LICENSE.MIT",)),)
HEADER = """Badi third-party notices
========================

Badi is MIT-licensed (see LICENSE). Its binaries include the open-source
components below, under the licences their authors published. The English
writing lexicon (SCOWL) has its own notices, installed beside this file.

Generated by scripts/third-party-notices.py from Cargo.lock for
{target}; run it again after a dependency changes.
"""


def cargo(*arguments):
    # Not --offline: metadata reads every platform's manifests, which a
    # host-only build never downloads. --locked keeps the resolution fixed.
    result = subprocess.run(["cargo", *arguments, "--locked", "--color", "never"], cwd=ROOT,
                            capture_output=True, text=True)
    if result.returncode:
        raise SystemExit(f"cargo {' '.join(arguments)} failed:\n{result.stderr}")
    return result.stdout


def shipped_crates():
    """(name, version) of every crate linked into the broker's binaries."""
    tree = cargo("tree", "-p", "badi-broker", "-e", "normal,no-proc-macro", "--target", TARGET,
                 "--prefix", "none")
    crates = set()
    for line in tree.splitlines():
        # "name vX.Y.Z", then "(path)" for a local crate or "(*)" for a repeat.
        parts = line.split()
        if len(parts) >= 2 and parts[1].startswith("v") and parts[0] != "badi-broker":
            crates.add((parts[0], parts[1][1:]))
    return sorted(crates)


def licence_texts(directory):
    return [(path.name, path.read_text(errors="replace"))
            for path in sorted(directory.iterdir())
            if path.is_file() and path.name.upper().startswith(LICENCE_FILES)]


def components():
    metadata = json.loads(cargo("metadata", "--format-version", "1"))
    packages = {(package["name"], package["version"]): package for package in metadata["packages"]}
    found = []
    for name, version in shipped_crates():
        package = packages[(name, version)]
        texts = licence_texts(Path(package["manifest_path"]).parent)
        texts += [(Path(path).name, (ROOT / path).read_text()) for path in EXTRA_TEXTS.get((name, version), ())]
        if not texts:
            raise SystemExit(f"{name} {version} publishes no licence text; add one to EXTRA_TEXTS")
        if not package.get("license"):
            raise SystemExit(f"{name} {version} declares no licence")
        found.append((name, version, package["license"], package.get("repository") or "", "", texts))
    for name, version, licence, repository, paths in NATIVE:
        texts = [(Path(path).name, (ROOT / path).read_text()) for path in paths]
        found.append((name, version, licence, repository, "compiled into the Fcitx addon", texts))
    return found


def render(found):
    lines = [HEADER.format(target=TARGET), "Components", "----------", ""]
    for name, version, licence, repository, note, _ in found:
        extra = [repository] if repository else []
        # MPL-2.0 section 3.2: tell recipients of the binary where the source is.
        if "MPL" in licence:
            extra.append(f"source: https://crates.io/crates/{name}/{version}")
        if note:
            extra.append(note)
        lines.append(f"{name} {version}  {licence}" + ("  " + "; ".join(extra) if extra else ""))
    lines += ["", "Licence texts", "-------------", ""]
    texts, users = {}, {}
    for name, version, _, _, _, published in found:
        for filename, text in published:
            text = "\n".join(line.rstrip() for line in text.strip("\n").splitlines())
            # Copies that differ only in wrapping or spacing are one text.
            digest = hashlib.sha256(" ".join(text.split()).encode()).hexdigest()
            texts.setdefault(digest, text)
            users.setdefault(digest, []).append(f"{name} {version} ({filename})")
    for digest, text in texts.items():
        lines += ["==> " + ", ".join(users[digest]), "", text, ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed file is out of date")
    arguments = parser.parse_args()
    notices = render(components())
    if arguments.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != notices:
            print("THIRD-PARTY-NOTICES.txt is out of date; run python3 scripts/third-party-notices.py",
                  file=sys.stderr)
            raise SystemExit(1)
        print("Third-party notices match Cargo.lock")
        return
    OUTPUT.write_text(notices)
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
